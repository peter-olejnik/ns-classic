#!/usr/bin/env bash
# Build the NS dedicated server image (localhost/ns-classic-server:latest),
# used by hosting/compose.yaml.
#
# The mod directory comes from dist/server/ns, assembled by mapmerge/merge.sh
# from builder/build.sh's dist/ns plus the custom maps. Override it with
# NS_DIR, e.g. NS_DIR=dist/ns for a server without custom maps.
#
# PLUGINS lists the plugins to add, space-separated, e.g. PLUGINS=amxmodx.
# Each is dist/plugins/<name>, built by plugins/<name>/build.sh, and copied
# over the mod directory in that order. Without PLUGINS the image has none.
#
# Then config/ (repo root) is copied over the mod directory, in the same
# layout (see config/README.md): each X.example is installed as X, unless
# you have your own config/X, which wins. Any other file you put in config/
# is copied as it is. Files under addons/<name>/ are only copied when a
# plugin provides addons/<name>. config/.env* are compose settings, never
# copied into the image.
#
# It also writes hosting/.env (HLDS_PORT and HLTV_PORT from config/.env.default
# and config/.env), which compose reads for the port mappings.
#
# Uses podman if available, otherwise docker; override with CONTAINER_ENGINE.
#
# Usage: hosting/build.sh [extra build args...]
#   e.g. hosting/build.sh --no-cache
#        hosting/build.sh env      only (re)write hosting/.env, no build
set -euo pipefail

repo_root="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
config="$repo_root/config"
ns_dir="${NS_DIR:-$repo_root/dist/server/ns}"
image="localhost/ns-classic-server:latest"
generated="# Generated by hosting/build.sh from config/.env.default and config/.env; edit those."

# Before config/ existed, your files were hosting/.env, server.cfg, motd.txt
# and overlay/. Move them there once.
for f in .env server.cfg motd.txt; do
  old="$repo_root/hosting/$f"
  [[ -f "$old" ]] || continue
  [[ "$f" == .env ]] && [[ "$(head -n 1 "$old")" == "$generated" ]] && continue
  if [[ -e "$config/$f" ]]; then
    echo "warning: both hosting/$f (old place) and config/$f exist; using config/$f, remove hosting/$f" >&2
  else
    mv "$old" "$config/$f"
    echo "Moved hosting/$f to config/$f"
  fi
done
if [[ -d "$repo_root/hosting/overlay" ]]; then
  rm -f "$repo_root/hosting/overlay/.placeholder"
  cp -an "$repo_root/hosting/overlay/." "$config/"
  rm -rf "$repo_root/hosting/overlay"
  echo "Moved hosting/overlay/ into config/"
fi

# hosting/.env: compose takes the port mappings from it (interpolation only
# reads the .env next to compose.yaml); compose.yaml passes the same values
# to the containers, so the two always agree.
env_get() { # env_get KEY: config/.env over config/.env.default
  local f line val=""
  for f in "$config/.env.default" "$config/.env"; do
    [[ -f "$f" ]] || continue
    while IFS= read -r line || [[ -n "$line" ]]; do
      line="${line%$'\r'}"
      [[ "$line" == "$1="* ]] && val="${line#*=}"
    done < "$f"
  done
  printf '%s' "$val"
}
{
  echo "$generated"
  echo "HLDS_PORT=$(env_get HLDS_PORT)"
  echo "HLTV_PORT=$(env_get HLTV_PORT)"
} > "$repo_root/hosting/.env"
[[ "${1:-}" == env ]] && exit 0

if [[ ! -f "$ns_dir/dlls/ns.so" ]]; then
  echo "error: $ns_dir/dlls/ns.so not found; run builder/build.sh, then mapmerge/merge.sh" >&2
  exit 1
fi

# The plugins, combined into one build context (empty without PLUGINS)
plugins_dir="$repo_root/dist/hosting-plugins"
rm -rf "$plugins_dir"
mkdir -p "$plugins_dir"
for p in ${PLUGINS:-}; do
  [[ -d "$repo_root/dist/plugins/$p" ]] ||
    { echo "error: dist/plugins/$p not found; run plugins/$p/build.sh first" >&2; exit 1; }
  cp -a "$repo_root/dist/plugins/$p/." "$plugins_dir/"
  echo "Plugin: $p"
done

# config/, resolved into one build context: your file, else the example
config_dir="$repo_root/dist/hosting-config"
rm -rf "$config_dir"
mkdir -p "$config_dir"
mine=() newer=()
while IFS= read -r -d '' f; do
  rel="${f#"$config"/}"
  case "$rel" in .env*|README.md|NUL) continue ;; esac
  if [[ "$rel" == addons/* ]]; then
    addon="${rel#addons/}" addon="${addon%%/*}"
    [[ -d "$plugins_dir/addons/$addon" || -d "$ns_dir/addons/$addon" ]] || continue
  fi
  dest="${rel%.example}"
  if [[ "$rel" == *.example ]]; then
    if [[ -e "$config/$dest" ]]; then
      [[ "$f" -nt "$config/$dest" ]] && newer+=("$dest")
      continue
    fi
  else
    mine+=("$rel")
  fi
  mkdir -p "$(dirname "$config_dir/$dest")"
  cp "$f" "$config_dir/$dest"
done < <(find "$config" -type f -print0 | sort -z)
if (( ${#mine[@]} )); then
  echo "Your configs (config/): ${mine[*]}"
fi
for f in "${newer[@]}"; do
  echo "note: config/$f.example changed after your config/$f; merge what you need from it"
done

engine="${CONTAINER_ENGINE:-$(command -v podman >/dev/null && echo podman || echo docker)}"

"$engine" build -f "$repo_root/hosting/Dockerfile" -t "$image" \
  --build-context ns="$ns_dir" --build-context plugins="$plugins_dir" \
  --build-context config="$config_dir" \
  "$@" "$repo_root/hosting"

echo "Built $image"
echo "Start it with: cd hosting && $engine compose up -d"
